namespace RipOff.Game
{
    /// <summary>
    /// Every name and identity a re-themed release changes, in one place (README "Branding").
    /// The executable name is the AssemblyName in RipOff.Game.csproj; the art is the vector shape set in
    /// <see cref="ShapeSet"/>; sounds are synthesized in RipOff.Core/Audio.
    /// </summary>
    public static class Branding
    {
        /// <summary>Shown in menus and lobby text.</summary>
        public const string GameName = "RIP-OFF REMAKE";
        /// <summary>Window title prefix.</summary>
        public const string WindowTitle = "Rip-Off (remake)";
        /// <summary>
        /// Tag written into every Steam lobby and required by every lobby search, plus the LiteNetLib connection key.
        /// App ID 480 is shared by every developer testing with Spacewar, so this must be unique to this game:
        /// lobbies without it never show up, and peers with a different key (or protocol version) are refused.
        /// </summary>
        public const string LobbyGameKey = "nhustak.ripoff-remake";
        /// <summary>Folder under the user's application-data folder for settings.json (SettingsStore).</summary>
        public const string SettingsFolder = "RipOffRemake";
        /// <summary>Steam App ID written to steam_appid.txt: 480 = Valve's public Spacewar test app.</summary>
        public const uint SteamAppId = 480;
        /// <summary>Vector art used by the scene: RipOff.Core.Shapes.ShapeData (generated by tools/remake/gen_shapes.py
        /// from disasm/shapes). A re-theme replaces that generated file (same Seg[] layout).</summary>
        public const string ShapeSet = "RipOff.Core.Shapes.ShapeData";
    }
}
