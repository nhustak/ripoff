#!/usr/bin/env python3
"""Generate src/RipOff.Core/Shapes/ShapeData.g.cs from our decoded docs
(disasm/shapes/objects.txt and disasm/shapes/shapes.txt). The game never reads the ROM:
this re-expresses the documented vector lists as C# data.
usage: python3 tools/remake/gen_shapes.py   (run from the repo root)"""
import ast, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
objs = (root / "disasm/shapes/objects.txt").read_text().splitlines()
shps = (root / "disasm/shapes/shapes.txt").read_text().splitlines()

def segs_obj(txt):
    out = []
    for s in txt.split(";"):
        s = s.strip()
        if not s: continue
        x1, y1, x2, y2, d = (int(v) for v in s.split(","))
        out.append((x1, y1, x2, y2, d))
    return out

sets = ["player1", "player2"] + [f"enemy{i}" for i in range(1, 7)]
body, a8, a9, rot, src = {}, {}, {}, {}, {}
for l in objs:
    if l.startswith("#") or not l.strip(): continue
    head, data = l.split(" : ", 1)
    p = head.split()
    name, part, idx, addr = p[0], p[1], int(p[2]), p[3]
    sg = segs_obj(data)
    if part == "body": body[name] = sg; src[name] = addr
    elif part == "anim8": a8.setdefault(name, []).append((addr, sg))
    elif part == "anim9": a9.setdefault(name, []).append((addr, sg))
    elif part == "shape": rot[name] = (addr, sg)

glyphs, cans = {}, {}
for l in shps:
    m = re.match(r"glyph\s+(\d+)\s+(\$\w+)-\$\w+\s+\d+ lines\s+(\[.*\])$", l)
    if m: glyphs[int(m.group(1))] = (m.group(2), ast.literal_eval(m.group(3))); continue
    m = re.match(r"glyph@\s+(\$\w+)-\$\w+\s+\d+ lines\s+(\[.*\])$", l)
    if m: cans[m.group(1)] = ast.literal_eval(m.group(2))

def arr(sg, dimcol=True):
    if dimcol:
        return "new Seg[] { " + ", ".join(f"new({a},{b},{c},{d},{'true' if e else 'false'})" for a, b, c, d, e in sg) + " }"
    return "new Seg[] { " + ", ".join(f"new({a[0]},{a[1]},{b[0]},{b[1]},false)" for a, b in sg) + " }"

o = ["// <auto-generated> by tools/remake/gen_shapes.py from disasm/shapes/objects.txt + shapes.txt.",
     "// Do not edit by hand. Re-expressed from our own decoded docs (NOTES §5, §9.4, §10); the ROM is never read.",
     "namespace RipOff.Core.Shapes", "{", "    public static partial class ShapeData", "    {"]
o.append("        /// <summary>Tank sets: 0 = player 1, 1 = player 2, 2..7 = enemy types 1..6. Pivot-relative, y up.</summary>")
o.append("        public static readonly Seg[][] Body = {")
for n in sets: o.append(f"            {arr(body[n])}, // {n} {src[n]}")
o.append("        };")
for nm, d in (("Anim8", a8), ("Anim9", a9)):
    o.append(f"        public static readonly Seg[][][] {nm} = {{")
    for n in sets:
        o.append(f"            new Seg[][] {{ // {n}")
        for addr, sg in d[n]: o.append(f"                {arr(sg)}, // {addr}")
        o.append("            },")
    o.append("        };")
o.append("        /// <summary>Score/text glyphs 0..12 (0-9 digits, 10/11 words, 12 '+'), absolute glyph units.</summary>")
o.append("        public static readonly Seg[][] Glyphs = {")
for i in range(13): o.append(f"            {arr(glyphs[i][1], False)}, // {i} {glyphs[i][0]}")
o.append("        };")
o.append("        /// <summary>Canister glyphs $172C, $1735, $173E, $1747 (glyph units, drawn at x/2-13, y/2-46).</summary>")
o.append("        public static readonly Seg[][] Canister = {")
for k in sorted(cans): o.append(f"            {arr(cans[k], False)}, // {k}")
o.append("        };")
o.append("        /// <summary>Enemy fire-line frames $1F89/$1F92/$1F9B/$1FA4 (pivot-relative).</summary>")
o.append("        public static readonly Seg[][] FireLine = {")
for k in ("rot_1F89", "rot_1F92", "rot_1F9B", "rot_1FA4"): o.append(f"            {arr(rot[k][1])}, // {rot[k][0]}")
o.append("        };")
o.append(f"        /// <summary>Rotated shape $1F68 (pivot-relative).</summary>")
o.append(f"        public static readonly Seg[] Rot1F68 = {arr(rot['rot_1F68'][1])};")
o.append(f"        /// <summary>Shape $1FAE (no header; raw coordinates). UNCHECKED: assumed explosion starburst.</summary>")
o.append(f"        public static readonly Seg[] Burst1FAE = {arr(rot['rot_1FAE'][1])};")
o += ["    }", "}", ""]
out = root / "src/RipOff.Core/Shapes/ShapeData.g.cs"
out.write_text("\n".join(o))
print("wrote", out, sum(len(v) for v in body.values()), "body segs")
